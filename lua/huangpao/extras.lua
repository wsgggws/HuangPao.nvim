local M = {}

-- Pure native-format builders; every concrete color comes from palette.lua.
function M.get(p)
  local function toml(values)
    local lines = {}
    for _, item in ipairs(values) do
      lines[#lines + 1] = ('%s = "%s"'):format(item[1], item[2])
    end
    return table.concat(lines, "\n") .. "\n"
  end
  local wezterm = '# Generated by scripts/export.lua.\n[metadata]\nname = "HuangPao"\n\n[colors]\n'
    .. toml({
      { "foreground", p.text },
      { "background", p.bg },
      { "cursor_bg", p.cursor },
      { "cursor_border", p.cursor },
      { "cursor_fg", p.bg },
      { "selection_bg", p.terminal.selection_bg },
      { "selection_fg", p.terminal.selection_fg },
      { "compose_cursor", p.red },
      { "split", p.border },
      { "scrollbar_thumb", p.border },
    })
  local ansi = { p.bg, p.red, p.green, p.yellow, p.blue, p.purple, p.aqua, p.text }
  local brights = { p.text_faint, p.red, p.green, p.yellow, p.blue, p.purple, p.aqua, p.text_strong }
  for _, item in ipairs({ { "ansi", ansi }, { "brights", brights } }) do
    wezterm = wezterm .. item[1] .. ' = ["' .. table.concat(item[2], '", "') .. '"]\n'
  end
  wezterm = wezterm .. '\n[colors.tab_bar]\nbackground = "' .. p.surface_alt .. '"\n'
  for _, item in ipairs({
    { "active_tab", p.text_strong, p.bg_selected },
    { "inactive_tab", p.text_muted, p.bg_alt },
    { "inactive_tab_hover", p.text, p.bg_highlight },
    { "new_tab", p.text_muted, p.bg_alt },
    { "new_tab_hover", p.text, p.bg_highlight },
  }) do
    wezterm = wezterm
      .. "\n[colors.tab_bar."
      .. item[1]
      .. "]\n"
      .. toml({ { "fg_color", item[2] }, { "bg_color", item[3] } })
  end
  local roles = {
    { "fg", p.text },
    { "bg", p.terminal.sidebar_bg },
    { "hl", p.red },
    { "fg+", p.text_strong },
    { "bg+", p.bg_selected },
    { "hl+", p.red },
    { "info", p.text_muted },
    { "prompt", p.green },
    { "pointer", p.red },
    { "marker", p.purple },
    { "spinner", p.yellow },
    { "header", p.yellow },
    { "border", p.border },
    { "label", p.blue },
    { "preview-label", p.blue },
    { "query", p.text_strong },
    { "disabled", p.text_faint },
    { "preview-bg", p.terminal.preview_bg },
    { "preview-fg", p.text },
    { "preview-border", p.border },
  }
  local fzf_colors = {}
  for _, item in ipairs(roles) do
    fzf_colors[#fzf_colors + 1] = item[1] .. ":" .. item[2]
  end
  local fzf = "FZF_THEME_NAME='HuangPao'\nFZF_THEME_COLOR='"
    .. table.concat(fzf_colors, ",")
    .. "'\nFZF_THEME_PREVIEW_CMD='COLORTERM=truecolor bat --color=always --style=numbers,changes --theme=HuangPao --paging=never --wrap=never --terminal-width=\"${FZF_PREVIEW_COLUMNS:-80}\" --'\n"
  local tmux = "# HuangPao status, terminal selection and popup surfaces; tmux 3.2+.\n"
    .. ("set -g status-style 'fg=%s,bg=%s'\n"):format(p.text_muted, p.surface_alt)
    .. ("set -g window-status-style 'fg=%s,bg=%s'\n"):format(p.text_muted, p.surface_alt)
    .. ("set -g window-status-current-style 'fg=%s,bg=%s,bold'\n"):format(p.text_strong, p.bg_selected)
    .. ("set -g window-status-activity-style 'fg=%s,bg=%s,underscore'\n"):format(p.blue, p.surface_alt)
    .. ("set -g window-status-bell-style 'fg=%s,bg=%s,bold'\n"):format(p.red, p.surface_alt)
    .. ("set -g message-style 'fg=%s,bg=%s'\n"):format(p.text, p.surface)
    .. ("set -g message-command-style 'fg=%s,bg=%s'\n"):format(p.orange, p.surface)
    .. ("set -g pane-border-style 'fg=%s'\n"):format(p.border_subtle)
    .. ("set -g pane-active-border-style 'fg=%s'\n"):format(p.orange)
    .. ("set -g mode-style 'fg=%s,bg=%s,bold'\n"):format(p.terminal.selection_fg, p.terminal.selection_bg)
    .. ("set -g popup-style 'fg=%s,bg=%s'\n"):format(p.text, p.surface)
    .. ("set -g popup-border-style 'fg=%s,bg=%s'\n"):format(p.border, p.surface)
  local oh_my_tmux = ('tmux_conf_theme_mode_fg="%s"\ntmux_conf_theme_mode_bg="%s"\n'):format(
    p.terminal.selection_fg,
    p.terminal.selection_bg
  )
  local palette = {
    p.bg,
    p.border,
    p.text_muted,
    p.blue,
    p.yellow,
    p.surface_alt,
    p.text,
    p.surface,
    p.yellow,
    p.orange,
    p.green,
    p.text_faint,
    p.text_muted,
    p.bg_alt,
    p.surface_alt,
    p.red,
    p.purple,
  }
  oh_my_tmux = ('status_line_theme="%s"\n'):format(p.surface_alt) .. oh_my_tmux
  for index, value in ipairs(palette) do
    oh_my_tmux = oh_my_tmux .. ('tmux_conf_theme_colour_%d="%s"\n'):format(index, value)
  end
  local outputs = {
    ["extras/wezterm/HuangPao.toml"] = wezterm,
    ["extras/fzf/huangpao.sh"] = fzf,
    ["extras/tmux/huangpao.conf"] = tmux,
    ["extras/tmux/huangpao.oh-my-tmux.conf"] = oh_my_tmux,
  }
  for path, content in pairs(require("huangpao.extras.native").get(p)) do
    outputs[path] = content
  end
  return outputs
end

return M
